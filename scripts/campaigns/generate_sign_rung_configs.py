#!/usr/bin/env python
"""Emit the per-connection signs rung's configs on the thermal cell at target 35.

The rung crosses three sign models -- random, the per-neuron atlas rule and the per-connection
table -- with two wirings, the wild type and the chemical-only null, each learning and frozen. The
random-sign wild type is the committed thermal target-35 pair; every other arm is that pair with
only the listed brain keys changed. Grounded signs are enforced, so PPO holds them. A test re-reads
every file through the real loader. A config that already exists is left alone.

Usage::

    uv run python scripts/campaigns/generate_sign_rung_configs.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
THERMAL = PROJECT_ROOT / "configs" / "scenarios" / "thermal_foraging"
_T = "connectomeppo_small_continuous2d_thermal_klinotaxis"
_NULL = {"wiring": "rewired_chemical_only"}
# Each grounded level runs at random signs' operating point: its chemical weights are scaled so the
# fraction of saturated units at initialisation matches random signs' (sign_scale_calibration.py,
# seeds 9601-9616). Grounded signs are mostly excitatory and otherwise saturate the settled network.
SIGNS: dict[str, dict[str, Any]] = {
    "random": {},
    "atlas": {
        "synapse_signs": "atlas",
        "enforce_synapse_signs": True,
        "chemical_weight_scale": 0.35,
    },
    "per_connection": {
        "synapse_signs": "per_connection",
        "enforce_synapse_signs": True,
        "chemical_weight_scale": 0.42,
    },
}
_TAG = {"random": "", "atlas": "_atlas_signs", "per_connection": "_per_connection_signs"}


def stem(signs: str, *, null: bool, frozen: bool) -> str:
    """Return one arm's config stem."""
    wiring = "_rewired_chemical_null" if null else ""
    floor = "_frozen" if frozen else ""
    return f"{_T}{wiring}{_TAG[signs]}{floor}_t35"


# Child stem -> (parent stem, brain-config changes). The random-sign wild type is the parent pair.
CHILDREN: dict[str, tuple[str, dict[str, Any]]] = {
    stem(signs, null=null, frozen=frozen): (
        stem("random", null=False, frozen=frozen),
        {**(_NULL if null else {}), **changes},
    )
    for signs, changes in SIGNS.items()
    for null in (False, True)
    for frozen in (False, True)
    if signs != "random" or null
}


def derive(child: str) -> tuple[Path, str]:
    """Build one config: its parent with its listed brain changes."""
    parent, changes = CHILDREN[child]
    data = yaml.safe_load((THERMAL / f"{parent}.yml").read_text())
    data["brain"]["config"].update(changes)
    header = (
        f"# Per-connection signs rung arm: {child}.\n#\n# Delta from {parent}.yml, and nothing else"
        " changes:\n"
        + "".join(f"#   brain.config.{k}: {v}\n" for k, v in changes.items())
        + "#\n# Generated by scripts/campaigns/generate_sign_rung_configs.py; re-checked through\n"
        "# the real config loader by test_sign_rung.py.\n#\n"
    )
    return THERMAL / f"{child}.yml", header + yaml.safe_dump(data, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    """CLI: write every missing config, and report what was already there."""
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.parse_args(argv)
    written = 0
    for child in CHILDREN:
        path, text = derive(child)
        if not path.exists():
            path.write_text(text)
            written += 1
    print(f"wrote {written} configs; kept {len(CHILDREN) - written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
