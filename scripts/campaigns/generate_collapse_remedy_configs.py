#!/usr/bin/env python
"""Emit M.1(b)'s configs: the placebo and each remedy round, on Logbook 092's body learners and the MLP.

Every config is one of 092's committed body configs (the wild type, the gap-only null, the MLP-PPO
control; Cook 2019, target 20) with only the listed brain keys changed. Each remedy round also carries the
placebo's shuffle stream, so a remedy and the placebo differ in the remedy alone. A config that already
exists is left alone, never overwritten.

Usage::

    uv run python scripts/campaigns/generate_collapse_remedy_configs.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
THERMAL = PROJECT_ROOT / "configs" / "scenarios" / "thermal_foraging"

_P = "connectomeppo_small_continuous2d_thermal_klinotaxis_body"
WILD_TYPE = f"{_P}_wt_ppo_t20"
GAP_ONLY = f"{_P}_gaponly_ppo_t20"
MLP = "mlpppo_small_continuous2d_thermal_klinotaxis_body_ppo_t20"
PARENTS: tuple[str, ...] = (WILD_TYPE, GAP_ONLY, MLP)

_PLACEBO: dict[str, Any] = {"rollout_shuffle_stream": True}
# Round -> its brain keys, in D25's order; each remedy carries the placebo's stream.
ROUNDS: dict[str, dict[str, Any]] = {
    "placebo": _PLACEBO,
    "klstop": {**_PLACEBO, "kl_stop_factor": 3.0},
    "wclip": {**_PLACEBO, "weight_clip": 2.0},
    "adam": {**_PLACEBO, "adam_eps": 1e-4, "adam_beta2": 0.99},
}


def stem(parent: str, round_name: str) -> str:
    """Return the config stem for one parent under one round."""
    return f"{parent.removesuffix('_t20')}_m1b_{round_name}_t20"


CHILDREN: dict[str, tuple[str, dict[str, Any]]] = {
    stem(parent, name): (parent, changes) for name, changes in ROUNDS.items() for parent in PARENTS
}


def derive(child: str) -> tuple[Path, str]:
    """Build one config: its parent with its listed brain changes."""
    parent, changes = CHILDREN[child]
    data = yaml.safe_load((THERMAL / f"{parent}.yml").read_text())
    data["brain"]["config"].update(changes)
    header = (
        f"# M.1(b) arm: {child}.\n#\n# Delta from {parent}.yml, and nothing else changes:\n"
        + "".join(f"#   brain.config.{k}: {v}\n" for k, v in changes.items())
        + "#\n# Generated by scripts/campaigns/generate_collapse_remedy_configs.py; re-checked\n"
        "# through the real config loader by test_collapse_remedy_configs.py.\n#\n"
    )
    return THERMAL / f"{child}.yml", header + yaml.safe_dump(data, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    """CLI: write every missing config, and report what was already there."""
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.parse_args(argv)
    written = 0
    for child in CHILDREN:
        path, text = derive(child)
        if not path.exists():
            path.write_text(text)
            written += 1
    print(f"wrote {written} configs; kept {len(CHILDREN) - written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
