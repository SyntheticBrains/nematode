#!/usr/bin/env python
"""Emit the body cell's wiring-contrast configs on Emmons 2024 with log-compressed gap counts.

The thermal cell through the kinematic body at target 20: the wild type and the gap-only null, each
learning and frozen. Each config is a committed body config with two keys changed — the connectome
source and the gap weight mode — and a loader test re-reads it. A config that already exists is left
alone, never overwritten.

Usage::

    uv run python scripts/campaigns/generate_body_logcount_configs.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
THERMAL = PROJECT_ROOT / "configs" / "scenarios" / "thermal_foraging"

_B = "connectomeppo_small_continuous2d_thermal_klinotaxis_body"
DELTA: dict[str, Any] = {
    "connectome_source": "emmons_2024_hermaphrodite",
    "gap_weight_mode": "log_count",
}
# Role -> (child stem, committed parent stem).
ARMS: dict[str, tuple[str, str]] = {
    "wt_learn": (f"{_B}_logcount_wt_ppo_t20", f"{_B}_wt_ppo_t20"),
    "wt_frozen": (f"{_B}_logcount_wt_frozen_t20", f"{_B}_wt_frozen_t20"),
    "rn_learn": (f"{_B}_logcount_gaponly_ppo_t20", f"{_B}_gaponly_ppo_t20"),
    "rn_frozen": (f"{_B}_logcount_gaponly_frozen_t20", f"{_B}_gaponly_frozen_t20"),
}


def derive(child: str, parent: str) -> tuple[Path, str]:
    """Build one config: its parent with the stated brain changes."""
    data = yaml.safe_load((THERMAL / f"{parent}.yml").read_text())
    data["brain"]["config"].update(DELTA)
    header = (
        f"# Body wiring-contrast arm on log-compressed gap counts: {child}.\n#\n"
        f"# Delta from {parent}.yml, and nothing else changes:\n"
        + "".join(f"#   brain.config.{k}: {v}\n" for k, v in DELTA.items())
        + "#\n# Generated by scripts/campaigns/generate_body_logcount_configs.py; re-checked through\n"
        "# the real config loader by test_body_logcount_configs.py.\n#\n"
    )
    return THERMAL / f"{child}.yml", header + yaml.safe_dump(data, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    """CLI: write every missing config, and report what was already there."""
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.parse_args(argv)
    written = 0
    for child, parent in ARMS.values():
        path, text = derive(child, parent)
        if not path.exists():
            path.write_text(text)
            written += 1
    print(f"wrote {written} configs; kept {len(ARMS) - written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
