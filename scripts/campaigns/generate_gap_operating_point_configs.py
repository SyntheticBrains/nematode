#!/usr/bin/env python
"""Emit G.0's configs: the gap model's operating point on the thermal cell at target 35, on Emmons.

Every arm is a committed thermal target-35 parent (the learning cell or its frozen floor) with only
the listed brain keys changed, each one moving the cell to the Emmons 2024 reconstruction first. A
test re-reads every file through the real loader to check it. A config that already exists is left
alone, never overwritten.

Arms, by level (``wt`` the wild type, ``gaponly`` the gap-only null):

* ``count`` -- today's gap weights: wild type and gap-only null, each learning and frozen. Also the
  Emmons anchor pilot's four arms.
* ``unit`` -- every existing gap pair weighted 1 before the normalisation: the same four arms.
* ``outliers_scattered`` and ``outliers_held`` -- the two gap-outlier nulls, learning and frozen,
  read against the ``count`` wild type.
* ``gap_off`` -- gap junctions off, learning and frozen; one brain, since with no gap junctions the
  wild type and the gap-only null coincide.
* the profile -- gap scale x0.25, x0.5, x2 and log-count weights, wild type and gap-only null, each
  learning.
* depth -- settling depths 2, 3 and 6, wild type and gap-only null, each learning.

Usage::

    uv run python scripts/campaigns/generate_gap_operating_point_configs.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
THERMAL = PROJECT_ROOT / "configs" / "scenarios" / "thermal_foraging"
_T = "connectomeppo_small_continuous2d_thermal_klinotaxis"
LEARN_PARENT = f"{_T}_t35"
FROZEN_PARENT = f"{_T}_frozen_t35"
PREFIX = f"{_T}_g0"

_EMMONS: dict[str, Any] = {"connectome_source": "emmons_2024_hermaphrodite"}
_GAP_ONLY: dict[str, Any] = {"wiring": "rewired_gap_junctions_only"}
# The wild type and the gap-only null at a level, before the level's own changes.
_WIRINGS: dict[str, dict[str, Any]] = {"wt": {}, "gaponly": _GAP_ONLY}

# Level -> the brain changes that define it, beyond the Emmons source.
FOUR_ARM_LEVELS: dict[str, dict[str, Any]] = {
    "count": {},
    "unit": {"gap_weight_mode": "unit"},
}
# Level -> the one wiring a single-null level learns and floors.
NULL_LEVELS: dict[str, dict[str, Any]] = {
    "outliers_scattered": {"wiring": "rewired_gap_outliers_scattered"},
    "outliers_held": {"wiring": "rewired_gap_outliers_held"},
    "gap_off": {"enable_gap_junctions": False},
}
PROFILE_LEVELS: dict[str, dict[str, Any]] = {
    "scale0p25": {"gap_weight_scale": 0.25},
    "scale0p5": {"gap_weight_scale": 0.5},
    "scale2": {"gap_weight_scale": 2.0},
    "log_count": {"gap_weight_mode": "log_count"},
    "depth2": {"forward_pass_depth": 2},
    "depth3": {"forward_pass_depth": 3},
    "depth6": {"forward_pass_depth": 6},
}


def _children() -> dict[str, tuple[str, dict[str, Any]]]:
    """Child stem -> (parent stem, brain-config changes)."""
    out: dict[str, tuple[str, dict[str, Any]]] = {}
    for level, changes in FOUR_ARM_LEVELS.items():
        for wiring, wiring_changes in _WIRINGS.items():
            delta = {**_EMMONS, **wiring_changes, **changes}
            out[f"{PREFIX}_{level}_{wiring}_t35"] = (LEARN_PARENT, delta)
            out[f"{PREFIX}_{level}_{wiring}_frozen_t35"] = (FROZEN_PARENT, delta)
    for level, changes in NULL_LEVELS.items():
        delta = {**_EMMONS, **changes}
        out[f"{PREFIX}_{level}_t35"] = (LEARN_PARENT, delta)
        out[f"{PREFIX}_{level}_frozen_t35"] = (FROZEN_PARENT, delta)
    for level, changes in PROFILE_LEVELS.items():
        for wiring, wiring_changes in _WIRINGS.items():
            delta = {**_EMMONS, **wiring_changes, **changes}
            out[f"{PREFIX}_{level}_{wiring}_t35"] = (LEARN_PARENT, delta)
    return out


CHILDREN: dict[str, tuple[str, dict[str, Any]]] = _children()


def derive(child: str) -> tuple[Path, str]:
    """Build one config: its parent with its listed brain changes."""
    parent, changes = CHILDREN[child]
    data = yaml.safe_load((THERMAL / f"{parent}.yml").read_text())
    data["brain"]["config"].update(changes)
    header = (
        f"# G.0 arm: {child}.\n#\n# Delta from {parent}.yml, and nothing else changes:\n"
        + "".join(f"#   brain.config.{k}: {v}\n" for k, v in changes.items())
        + "#\n# Generated by scripts/campaigns/generate_gap_operating_point_configs.py; re-checked\n"
        "# through the real config loader by test_gap_operating_point_configs.py.\n#\n"
    )
    return THERMAL / f"{child}.yml", header + yaml.safe_dump(data, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    """CLI: write every missing config, and report what was already there."""
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.parse_args(argv)
    written = 0
    for child in CHILDREN:
        path, text = derive(child)
        if not path.exists():
            path.write_text(text)
            written += 1
    print(f"wrote {written} configs; kept {len(CHILDREN) - written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
