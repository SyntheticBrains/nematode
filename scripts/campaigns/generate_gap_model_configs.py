#!/usr/bin/env python
"""Emit the strength-normalised gap model's configs on the thermal cell at target 35, on Emmons 2024.

The wild type and the gap-only null, each learning and frozen, with count weights and
``gap_normalisation: strength``. Each config is a committed thermal config with only the listed keys
changed, and a loader test re-reads it. A config that already exists is left alone, never
overwritten. The ohmic model's configs are the gap-substrate generator's, used as they stand.

Usage::

    uv run python scripts/campaigns/generate_gap_model_configs.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
THERMAL = PROJECT_ROOT / "configs" / "scenarios" / "thermal_foraging"

_T = "connectomeppo_small_continuous2d_thermal_klinotaxis"
_STRENGTH: dict[str, Any] = {
    "connectome_source": "emmons_2024_hermaphrodite",
    "gap_normalisation": "strength",
}
_GAP_ONLY: dict[str, Any] = {"wiring": "rewired_gap_junctions_only"}
_PARENTS: dict[str, str] = {"learn": f"{_T}_t35", "frozen": f"{_T}_frozen_t35"}

# Role -> (child stem, parent stem, brain-config changes).
ARMS: dict[str, tuple[str, str, dict[str, Any]]] = {
    f"{w}_{k}": (
        f"{_T}_g0b_strength_{tag}{'_frozen' if k == 'frozen' else ''}_t35",
        _PARENTS[k],
        {**_STRENGTH, **wiring},
    )
    for w, tag, wiring in (("wt", "wt", {}), ("rn", "gaponly", _GAP_ONLY))
    for k in ("learn", "frozen")
}


def derive(child: str, parent: str, changes: dict[str, Any]) -> tuple[Path, str]:
    """Build one config: its parent with the listed brain changes."""
    data = yaml.safe_load((THERMAL / f"{parent}.yml").read_text())
    data["brain"]["config"].update(changes)
    header = (
        f"# Strength-normalised gap model arm: {child}.\n#\n"
        f"# Delta from {parent}.yml, and nothing else changes:\n"
        + "".join(f"#   brain.config.{k}: {v}\n" for k, v in changes.items())
        + "#\n# Generated by scripts/campaigns/generate_gap_model_configs.py; re-checked through\n"
        "# the real config loader by test_gap_model_configs.py.\n#\n"
    )
    return THERMAL / f"{child}.yml", header + yaml.safe_dump(data, sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    """CLI: write every missing config, and report what was already there."""
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.parse_args(argv)
    written = 0
    for child, parent, changes in ARMS.values():
        path, text = derive(child, parent, changes)
        if not path.exists():
            path.write_text(text)
            written += 1
    print(f"wrote {written} configs; kept {len(ARMS) - written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
